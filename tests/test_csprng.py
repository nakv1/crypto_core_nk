import pytest

from cryptocore.csprng import RandomGenerationError, generate_random_bytes


@pytest.fixture(scope="module")
def random_keys():
    return [generate_random_bytes(16) for _ in range(1000)]


@pytest.mark.parametrize(
    ("value", "error_type"),
    [
        ("16", TypeError),
        (1.5, TypeError),
        (None, TypeError),
        (True, TypeError),
        (False, TypeError),
        (-1, ValueError),
    ],
)
def test_generate_random_bytes_rejects_invalid_value_without_calling_os(
    value, error_type, monkeypatch
):
    def reject_call(size):
        raise AssertionError(f"os.urandom must not be called: {size}")

    monkeypatch.setattr("cryptocore.csprng.os.urandom", reject_call)

    with pytest.raises(error_type):
        generate_random_bytes(value)


def test_generate_random_bytes_accepts_zero():
    assert generate_random_bytes(0) == b""


@pytest.mark.parametrize("size", [1, 16, 31, 64])
def test_generate_random_bytes_returns_bytes_of_requested_length(size):
    result = generate_random_bytes(size)

    assert type(result) is bytes
    assert len(result) == size


def test_generate_random_bytes_calls_os_urandom_with_requested_length(monkeypatch):
    requested_sizes = []
    expected = b"generated bytes"

    def fake_urandom(size):
        requested_sizes.append(size)
        return expected

    monkeypatch.setattr("cryptocore.csprng.os.urandom", fake_urandom)

    result = generate_random_bytes(len(expected))

    assert result == expected
    assert requested_sizes == [len(expected)]


@pytest.mark.parametrize("error_type", [OSError, NotImplementedError])
def test_generate_random_bytes_wraps_expected_system_error(error_type, monkeypatch):
    original_error = error_type("system details")

    def raise_system_error(size):
        raise original_error

    monkeypatch.setattr("cryptocore.csprng.os.urandom", raise_system_error)

    with pytest.raises(
        RandomGenerationError, match="^failed to generate random bytes$"
    ) as error:
        generate_random_bytes(16)

    assert error.value.__cause__ is original_error


def test_generate_random_bytes_does_not_wrap_unexpected_runtime_error(monkeypatch):
    def raise_unexpected_error(size):
        raise RuntimeError("unexpected bug")

    monkeypatch.setattr("cryptocore.csprng.os.urandom", raise_unexpected_error)

    with pytest.raises(RuntimeError, match="^unexpected bug$") as error:
        generate_random_bytes(16)

    assert type(error.value) is RuntimeError
    assert not isinstance(error.value, RandomGenerationError)
    assert str(error.value) == "unexpected bug"


def test_generated_keys_are_unique(random_keys):
    assert len(set(random_keys)) == 1000


def test_generated_keys_have_balanced_hamming_weight(random_keys):
    one_bits = sum(byte.bit_count() for key in random_keys for byte in key)
    total_bits = len(random_keys) * 16 * 8

    assert 0.45 <= one_bits / total_bits <= 0.55
